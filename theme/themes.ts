export function getTheme(name: "light" | "dark"): ThemeTokens {
  return name === "dark" ? darkTheme : lightTheme;
}

export function getSubTheme(
  parent: "light" | "dark",
  subTheme: string | null,
): ThemeTokens {
  if (!subTheme) return getTheme(parent);
  if (subTheme === "dark") return darkTheme;
  if (subTheme === "red")
    return parent === "dark" ? darkRedTheme : lightRedTheme;
  if (subTheme === "alt1_Button")
    return parent === "dark" ? darkButtonTheme : lightTheme;
  return getTheme(parent);
}
